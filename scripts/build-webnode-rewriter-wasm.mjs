// Builds webnode's module rewriter (src/core/webnode/process/loader/rewriter/crate,
// Rust) to the committed module in
// src/core/webnode/process/loader/rewriter/wasm.generated.ts.
//
//   bun run build:webnode-rewriter
//
// Two stages: `cargo build` for wasm32-unknown-unknown (stable Rust; the first
// build fetches the oxc parser crates, so it needs the network once), then
// `wasm-opt` (Binaryen) to shrink the module. The result is committed so tests
// and deploys need no Rust toolchain; only regenerating it does. Requires the
// wasm32-unknown-unknown target (`rustup target add wasm32-unknown-unknown`)
// and `wasm-opt`.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const moduleDir = resolve(root, "src/core/webnode/process/loader/rewriter");
const crateDir = resolve(moduleDir, "crate");
const rawWasm = resolve(crateDir, "target/wasm32-unknown-unknown/release/webnode_rewriter.wasm");
const outFile = resolve(moduleDir, "wasm.generated.ts");

/** Every file the module is built from, relative to the module's directory. */
function sourceFiles() {
  const rust = (directory) =>
    readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) {
        return rust(path);
      }
      return entry.name.endsWith(".rs") ? [path] : [];
    });
  return [
    join(crateDir, "Cargo.toml"),
    join(crateDir, "Cargo.lock"),
    ...rust(join(crateDir, "src")).sort(),
  ].map((path) => relative(moduleDir, path).split("\\").join("/"));
}

execFileSync("cargo", ["build", "--release", "--target", "wasm32-unknown-unknown"], {
  cwd: crateDir,
  stdio: "inherit",
});

const scratch = mkdtempSync(join(tmpdir(), "webnode-rewriter-"));
let wasm;
try {
  const optimized = join(scratch, "rewriter.wasm");
  // Rust's wasm32 target uses what every browser this runs in has had for
  // years (bulk memory, sign extension, saturating conversions).
  execFileSync("wasm-opt", ["-Os", "--all-features", rawWasm, "-o", optimized], {
    stdio: "inherit",
  });
  wasm = readFileSync(optimized);
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
// It must be a module: a broken build is not committed.
new WebAssembly.Module(wasm);

const files = sourceFiles();
const hash = createHash("sha256");
for (const file of files) {
  hash.update(file);
  hash.update("\0");
  hash.update(readFileSync(resolve(moduleDir, file)));
  hash.update("\0");
}

writeFileSync(
  outFile,
  `// Generated by scripts/build-webnode-rewriter-wasm.mjs from rewriter/crate. Do not edit:
// change the Rust source and run \`bun run build:webnode-rewriter\`.

/** The rewriter module, base64. It imports nothing and exports its memory and the \`wnr_\` calls. */
export const REWRITER_WASM_BASE64 =
  "${wasm.toString("base64")}";

/** The files it was built from, and a SHA-256 over their names and contents. */
export const REWRITER_SOURCE_FILES = ${JSON.stringify(files, null, 2)};
export const REWRITER_SOURCE_HASH = "${hash.digest("hex")}";
`,
);
console.log(`${relative(root, outFile)}: ${(wasm.length / 1024).toFixed(0)} KB of WebAssembly`);
