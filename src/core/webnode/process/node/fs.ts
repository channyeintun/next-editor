// Node defines these as accessors; assigning one (graceful-fs does) replaces it.
for (const name of ["ReadStream", "WriteStream", "FileReadStream", "FileWriteStream"] as const) {
  let value: unknown = fs[name];
  Object.defineProperty(fs, name, {
    configurable: true,
    enumerable: true,
    get: () => value,
    set: (next: unknown) => {
      value = next;
    },
  });
}
Object.defineProperty(fs, "promises", {
  configurable: true,
  enumerable: true,
  get: () => promises,
});

// Streams do their I/O through this object, so patches to `fs.read` & co reach them.
setStreamFs(fs as unknown as StreamFs);

